// Builds src/data/syncMap.js: a grid of real simulations over coupling K and
// individuality σ (global coupling, no noise). Usage:  npm run map
//
// Each cell: N = 200 fireflies, 60 s of simulated time, r averaged over the
// last 20 s. Seeds are fixed, so the file is reproducible.
import { writeFileSync } from 'node:fs';
import { Simulation } from '../src/worlds/firefly/simulation.js';
import { defaultParams, GLOBAL_RADIUS } from '../src/worlds/firefly/parameters.js';

const N = 200;
const BURN_IN = 40;
const AVERAGE = 20;
const Ks = Array.from({ length: 21 }, (_, i) => +(i * 0.15).toFixed(2));        // 0 … 3
const sigmas = Array.from({ length: 20 }, (_, j) => +((j + 1) * 0.05).toFixed(2)); // 0.05 … 1

const t0 = Date.now();
let seed = 5000;
const rows = [];
for (const sigma of sigmas) {
  const row = [];
  for (const K of Ks) {
    const sim = new Simulation(
      { ...defaultParams(), count: N, radius: GLOBAL_RADIUS, coupling: K, freqSpread: sigma, noise: 0 },
      seed++,
    );
    sim.runFor(BURN_IN);
    let sum = 0;
    let n = 0;
    for (let k = 0; k < AVERAGE * 5; k++) {
      sim.runFor(0.2);
      sum += sim.order().r;
      n++;
    }
    row.push(+(sum / n).toFixed(3));
  }
  rows.push(row);
}

const body = `// GENERATED by scripts/build-sync-map.mjs (npm run map). Do not edit by hand.
// Mean order parameter r over the last ${AVERAGE} s of a ${BURN_IN + AVERAGE} s simulation,
// N = ${N}, global coupling, no noise. rows: σ (individuality), columns: K (coupling).
export const SYNC_MAP = {
  n: ${N},
  seconds: ${BURN_IN + AVERAGE},
  Ks: ${JSON.stringify(Ks)},
  sigmas: ${JSON.stringify(sigmas)},
  r: [
${rows.map((r) => `    ${JSON.stringify(r)},`).join('\n')}
  ],
};
`;
writeFileSync(new URL('../src/data/syncMap.js', import.meta.url), body);
console.log(`wrote ${rows.length * Ks.length} cells in ${((Date.now() - t0) / 1000).toFixed(1)} s`);
